-- =====================================================================
-- V6__fare_rules.sql
-- Tạo bảng fare_rules (quy định/quyền lợi của loại vé, có version) và
-- seed 1 rule mặc định cho mỗi fare_class hiện có.
--
-- Chính sách hoàn vé nằm ở đây; booking_segments lưu fare_rule_id để đổi
-- rule sau này không ảnh hưởng vé đã bán.
-- =====================================================================

CREATE TABLE fare_rules (
    id                              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fare_class_id                   BIGINT       NOT NULL REFERENCES fare_classes (id),
    version                         INTEGER      NOT NULL CHECK (version >= 1),
    is_refundable                   BOOLEAN      NOT NULL,
    refund_min_hours_before_departure INTEGER    NOT NULL CHECK (refund_min_hours_before_departure >= 0),
    refund_percent                  NUMERIC(5, 2) NOT NULL CHECK (refund_percent BETWEEN 0 AND 100),
    description                     VARCHAR(500),
    effective_from                  TIMESTAMPTZ  NOT NULL,
    is_active                       BOOLEAN      NOT NULL DEFAULT true,
    is_deleted                      BOOLEAN      NOT NULL DEFAULT false,
    deleted_at                      TIMESTAMPTZ,
    created_at                      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at                      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- một loại vé không có 2 version trùng số
    UNIQUE (fare_class_id, version)
);

CREATE INDEX idx_fare_rules_fare_class_id ON fare_rules (fare_class_id);

-- Seed rule mặc định (version 1) cho mỗi loại vé đang có.
-- ECONOMY/PREMIUM_ECONOMY: hoàn được, hủy trước 24h hoàn 80%.
-- BUSINESS: hoàn được, hủy trước 24h hoàn 90%.
INSERT INTO fare_rules
    (fare_class_id, version, is_refundable, refund_min_hours_before_departure, refund_percent, description, effective_from)
SELECT
    fc.id,
    1,
    true,
    24,
    CASE fc.fare_class_code
        WHEN 'BUSINESS' THEN 90
        ELSE 80
    END,
    'Chính sách hoàn vé mặc định',
    now()
FROM fare_classes fc;
