-- ---------------------------------------------------------------------
-- 1. Tiền tố hãng cho mã hạng vé
-- ---------------------------------------------------------------------
-- Bỏ index cũ trước khi đổi dữ liệu.
DROP INDEX IF EXISTS uq_fare_classes_code_per_airline;

-- Chỉ thêm tiền tố cho mã CHƯA có, để chạy lại an toàn (idempotent).
-- Áp cho cả dòng đã xóa mềm để mã không bao giờ trùng khi khôi phục.
UPDATE fare_classes fc
SET fare_class_code = a.airline_code || '_' || fc.fare_class_code,
    updated_at      = now()
FROM airlines a
WHERE a.id = fc.airline_id
  AND left(fc.fare_class_code, length(a.airline_code) + 1) <> a.airline_code || '_';

CREATE UNIQUE INDEX uq_fare_classes_code_active
    ON fare_classes (fare_class_code)
    WHERE is_deleted = false;

-- ---------------------------------------------------------------------
-- 2. notifications
-- ---------------------------------------------------------------------
CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL REFERENCES users (id),
    type        VARCHAR(40)  NOT NULL,
    title       VARCHAR(200) NOT NULL,
    body        VARCHAR(500),
    link_url    VARCHAR(300),
    is_read     BOOLEAN      NOT NULL DEFAULT false,
    read_at     TIMESTAMPTZ,
    dedupe_key  VARCHAR(120),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT notifications_type_check CHECK (type IN (
        'FLIGHT_SCHEDULE_CHANGED',
        'FLIGHT_DELAYED',
        'FLIGHT_CANCELLED',
        'BOOKING_PAYMENT_EXPIRING',
        'BOOKING_CONFIRMED',
        'BOOKING_CANCELLED',
        'ETICKET_ISSUED',
        'VOUCHER_ASSIGNED',
        'VOUCHER_EXPIRING'
    ))
);

-- Danh sách + đếm chưa đọc của một user (endpoint FE gọi mỗi 60 giây).
CREATE INDEX idx_notifications_user_read_created
    ON notifications (user_id, is_read, created_at DESC);

-- Chống phát trùng (callback thanh toán đến 2 lần, job chạy lặp).
CREATE UNIQUE INDEX uq_notifications_dedupe
    ON notifications (user_id, dedupe_key)
    WHERE dedupe_key IS NOT NULL;

-- Job xóa cứng bản ghi quá 90 ngày quét theo created_at.
CREATE INDEX idx_notifications_created_at ON notifications (created_at);
