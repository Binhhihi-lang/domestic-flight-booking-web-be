-- =====================================================================
-- V9__wallets.sql
-- Tạo ví khách hàng (wallets) + sổ giao dịch (wallet_transactions).
-- Tiền hoàn khi hủy vé được cộng vào ví. Mỗi CUSTOMER có đúng 1 ví,
-- tạo cùng giao dịch với đăng ký; với khách đã có sẵn thì tạo ví số dư 0.
-- =====================================================================

CREATE TABLE wallets (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL UNIQUE REFERENCES users (id),
    balance    NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    currency   VARCHAR(3)   NOT NULL DEFAULT 'VND',
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE wallet_transactions (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_id        BIGINT       NOT NULL REFERENCES wallets (id),
    booking_id       BIGINT REFERENCES bookings (id),
    transaction_type VARCHAR(20)  NOT NULL CHECK (transaction_type IN ('REFUND_CREDIT')),
    amount           NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    balance_after    NUMERIC(12, 2) NOT NULL CHECK (balance_after >= 0),
    description      VARCHAR(255),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_wallet_transactions_wallet_id ON wallet_transactions (wallet_id);

-- mỗi booking chỉ được hoàn tiền một lần
CREATE UNIQUE INDEX uq_wallet_transactions_refund_per_booking
    ON wallet_transactions (booking_id) WHERE transaction_type = 'REFUND_CREDIT';

-- tạo ví số dư 0 cho mọi CUSTOMER hiện có
INSERT INTO wallets (user_id)
SELECT u.id
FROM users u
JOIN roles r ON r.id = u.role_id
WHERE r.name = 'CUSTOMER' AND u.is_deleted = false;
