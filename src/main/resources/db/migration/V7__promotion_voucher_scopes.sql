ALTER TABLE user_vouchers ADD CONSTRAINT user_vouchers_status_check
    CHECK (status IN ('AVAILABLE', 'RESERVED', 'USED', 'EXPIRED'));

-- ---- chuyển dữ liệu voucher_usages → user_vouchers rồi DROP ----
-- Nếu user đã có sẵn dòng ví cho voucher đó thì cập nhật thành USED;
-- nếu chưa có thì tạo mới. (V1–V3 không seed voucher nên thường bảng trống.)
UPDATE user_vouchers uv
SET status          = 'USED',
    booking_id      = vu.booking_id,
    discount_amount = vu.discount_amount,
    used_at         = vu.used_at
FROM voucher_usages vu
WHERE uv.user_id = vu.user_id AND uv.voucher_id = vu.voucher_id;

INSERT INTO user_vouchers (user_id, voucher_id, status, source, received_at, booking_id, discount_amount, used_at)
SELECT vu.user_id, vu.voucher_id, 'USED', 'CLAIMED', vu.used_at, vu.booking_id, vu.discount_amount, vu.used_at
FROM voucher_usages vu
WHERE NOT EXISTS (
    SELECT 1 FROM user_vouchers uv
    WHERE uv.user_id = vu.user_id AND uv.voucher_id = vu.voucher_id
);

DROP TABLE voucher_usages;
