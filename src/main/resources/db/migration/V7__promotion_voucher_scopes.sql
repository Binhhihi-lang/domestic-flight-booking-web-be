-- ========== 1. Bảng phạm vi & loại trừ ==========

CREATE TABLE promotion_scopes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_id         BIGINT      NOT NULL REFERENCES promotions (id),
    target_type          VARCHAR(15) NOT NULL CHECK (target_type IN ('AIRLINE', 'FARE_CLASS', 'ROUTE', 'FLIGHT')),
    airline_id           BIGINT REFERENCES airlines (id),
    fare_class_id        BIGINT REFERENCES fare_classes (id),
    flight_id            BIGINT REFERENCES flights (id),
    departure_airport_id BIGINT REFERENCES airports (id),
    arrival_airport_id   BIGINT REFERENCES airports (id),
    -- mỗi dòng chỉ dùng đúng các cột khóa ngoại của loại phạm vi tương ứng
    CONSTRAINT promotion_scopes_target_check CHECK (
        (target_type = 'AIRLINE'    AND airline_id IS NOT NULL
            AND fare_class_id IS NULL AND flight_id IS NULL
            AND departure_airport_id IS NULL AND arrival_airport_id IS NULL)
        OR (target_type = 'FARE_CLASS' AND fare_class_id IS NOT NULL
            AND airline_id IS NULL AND flight_id IS NULL
            AND departure_airport_id IS NULL AND arrival_airport_id IS NULL)
        OR (target_type = 'FLIGHT'     AND flight_id IS NOT NULL
            AND airline_id IS NULL AND fare_class_id IS NULL
            AND departure_airport_id IS NULL AND arrival_airport_id IS NULL)
        OR (target_type = 'ROUTE'      AND departure_airport_id IS NOT NULL
            AND airline_id IS NULL AND fare_class_id IS NULL AND flight_id IS NULL)
    )
);
CREATE INDEX idx_promotion_scopes_promotion_id ON promotion_scopes (promotion_id);

CREATE TABLE voucher_scopes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    voucher_id           BIGINT      NOT NULL REFERENCES vouchers (id),
    target_type          VARCHAR(15) NOT NULL CHECK (target_type IN ('AIRLINE', 'FARE_CLASS', 'ROUTE', 'FLIGHT')),
    airline_id           BIGINT REFERENCES airlines (id),
    fare_class_id        BIGINT REFERENCES fare_classes (id),
    flight_id            BIGINT REFERENCES flights (id),
    departure_airport_id BIGINT REFERENCES airports (id),
    arrival_airport_id   BIGINT REFERENCES airports (id),
    CONSTRAINT voucher_scopes_target_check CHECK (
        (target_type = 'AIRLINE'    AND airline_id IS NOT NULL
            AND fare_class_id IS NULL AND flight_id IS NULL
            AND departure_airport_id IS NULL AND arrival_airport_id IS NULL)
        OR (target_type = 'FARE_CLASS' AND fare_class_id IS NOT NULL
            AND airline_id IS NULL AND flight_id IS NULL
            AND departure_airport_id IS NULL AND arrival_airport_id IS NULL)
        OR (target_type = 'FLIGHT'     AND flight_id IS NOT NULL
            AND airline_id IS NULL AND fare_class_id IS NULL
            AND departure_airport_id IS NULL AND arrival_airport_id IS NULL)
        OR (target_type = 'ROUTE'      AND departure_airport_id IS NOT NULL
            AND airline_id IS NULL AND fare_class_id IS NULL AND flight_id IS NULL)
    )
);
CREATE INDEX idx_voucher_scopes_voucher_id ON voucher_scopes (voucher_id);

CREATE TABLE promotion_excluded_flights (
    promotion_id BIGINT NOT NULL REFERENCES promotions (id),
    flight_id    BIGINT NOT NULL REFERENCES flights (id),
    PRIMARY KEY (promotion_id, flight_id)
);

CREATE TABLE voucher_excluded_flights (
    voucher_id BIGINT NOT NULL REFERENCES vouchers (id),
    flight_id  BIGINT NOT NULL REFERENCES flights (id),
    PRIMARY KEY (voucher_id, flight_id)
);

